using MAGEMin_C
using MAGEMin_C: db_infos, ss_infos, db_registry, MAGEMIN_DATABASES,
                 harvest_db_infos, harvest_oxide_list, harvest_phase_oxide_support

const OUT_PATH = normpath(joinpath(@__DIR__, "..", "julia", "db_infos_generated.jl"))

"Emit a Vector{String} as a Julia literal."
strvec(v) = "[" * join(("\"" * s * "\"" for s in v), ", ") * "]"

function emit_ss(io, ss :: ss_infos)
    print(io, "        ss_infos(\"", ss.ss_fName, "\", \"", ss.ss_name, "\", ",
              ss.n_em, ", ", ss.n_xeos, ", ", ss.n_sf, ",\n")
    print(io, "                 ", strvec(ss.ss_em),   ",\n")
    print(io, "                 ", strvec(ss.ss_xeos), ",\n")
    print(io, "                 ", strvec(ss.ss_sf),   "),\n")
end

function emit_db(io, db :: db_infos)
    print(io, "    db_infos(\"", db.db_name, "\", \"", db.db_info, "\", ",
              db.db_dataset, ", ", db.dataset_opt, ",\n")
    print(io, "    ss_infos[\n")
    for ss in db.data_ss
        emit_ss(io, ss)
    end
    print(io, "    ],\n")
    print(io, "    ", strvec(db.ss_name),  ",\n")
    print(io, "    ", strvec(db.data_pp), "),\n")
end

function main()
    println(" Harvesting database information from the compiled library...")
    infos   = db_infos[]
    oxides  = Pair{String,Vector{String}}[]
    support = Pair{String,Dict{String,Set{String}}}[]
    t0 = time()
    for reg in MAGEMIN_DATABASES
        t = @elapsed begin
            push!(infos,   harvest_db_infos(reg.db_name))
            push!(oxides,  reg.db_name => harvest_oxide_list(reg.db_name))
            push!(support, reg.db_name => harvest_phase_oxide_support(reg.db_name))
        end
        println("   ", rpad(reg.db_name, 8), round(t * 1000, digits = 1), " ms")
    end
    println(" ", length(infos), " databases harvested in ", round(time() - t0, digits = 2), " s")

    open(OUT_PATH, "w") do io
        print(io, """
#=~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
#
#   Project      : MAGEMin_C
#   License      : GNU GENERAL PUBLIC LICENSE Version 3, 29 June 2007
#
# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~ =#
#
#   DO NOT EDIT BY HAND.
#
#   Generated by gen/generate_db_infos.jl by reading the compiled libMAGEMin.
#   Regenerate it whenever the C database definitions change:
#
#       make USE_MPI=0 lib && julia --project=. gen/generate_db_infos.jl
#
#   Rows are in MAGEMIN_DATABASES order (julia/database_registry.jl); db_name,
#   db_info, db_dataset and dataset_opt come from that registry, everything else
#   from the library. test/test_db_infos.jl fails if the two disagree.
#

const DB_INFOS_GENERATED = db_infos[
""")
        for db in infos
            emit_db(io, db)
        end
        print(io, "]\n\nconst DB_OXIDES_GENERATED = Dict{String,Vector{String}}(\n")
        w = maximum(length(first(p)) for p in oxides) + 2
        for (name, ox) in oxides
            print(io, "    ", rpad("\"" * name * "\"", w), " => ", strvec(ox), ",\n")
        end
        print(io, ")\n\nconst DB_PHASE_OXIDES_GENERATED = Dict{String,Dict{String,Set{String}}}(\n")
        for (name, sup) in support
            print(io, "    \"", name, "\" => Dict{String,Set{String}}(\n")
            pw = maximum(length(k) for k in keys(sup)) + 2
            for ph in sort(collect(keys(sup)))
                print(io, "        ", rpad("\"" * ph * "\"", pw), " => Set([",
                      join(("\"" * o * "\"" for o in sort(collect(sup[ph]))), ", "), "]),\n")
            end
            print(io, "    ),\n")
        end
        print(io, ")\n")
    end
    println(" Wrote ", OUT_PATH, " (", filesize(OUT_PATH) ÷ 1024, " KiB)")
end

main()

# --- mineral-name tables -----------------------------------------------------------
# em_name.json / ss_name.json used to be hand-maintained copies in both repos. They are
# now the join of three sources: the library (which names exist, and their compositions),
# MAGEMin_Warr2021_mapping.csv (full mineral names), and SOLVUS_FAMILY (solvus daughters).

using MAGEMin_C: EM_COMP_BASIS, SOLVUS_FAMILY, harvest_em_compositions,
                 retrieve_solution_phase_information, get_db_list

jstr(s)  = '"' * replace(s, '\\' => "\\\\", '"' => "\\\"") * '"'
jarr(v)  = "[" * join(v, ", ") * "]"
jnum(x)  = (y = round(x, digits = 10); y == round(y) ? string(Int(round(y))) : string(y))

function read_warr_names()
    path = normpath(joinpath(@__DIR__, "..", "julia", "MAGEMin_Warr2021_mapping.csv"))
    names = Dict{String,String}()
    for line in eachline(path)
        (startswith(line, '#') || isempty(strip(line))) && continue
        p = split(line, ',')
        length(p) < 4 && continue
        n = strip(p[1]); n == "magemin_name" && continue
        haskey(names, n) || (names[n] = String(strip(p[3])))
    end
    return names
end

function write_name_tables()
    full = read_warr_names()

    comps  = Dict{String,Dict{String,Vector{Float64}}}()
    for db in get_db_list()
        comps[db] = harvest_em_compositions(db)
    end

    # one composition per name: prefer the union database, else the first that defines it
    order  = vcat("all", [d for d in get_db_list() if d != "all"])
    pick   = Dict{String,Vector{Float64}}()
    ambig  = String[]
    allnm  = sort(unique(reduce(vcat, [collect(keys(c)) for c in values(comps)])))
    for n in allnm
        occ = [(db, comps[db][n]) for db in order if haskey(comps[db], n)]
        pick[n] = occ[1][2]
        # sb24 re-expresses FeO+O as Fe+O, so it differs by basis, not by model
        gen = [v for (db, v) in occ if db != "sb24"]
        length(gen) > 1 && any(!isapprox(v, gen[1]; atol = 1e-10) for v in gen) && push!(ambig, n)
    end

    em_path = normpath(joinpath(@__DIR__, "..", "julia", "em_name.json"))
    open(em_path, "w") do io
        println(io, "{")
        println(io, jstr("_header_"), ": [", jstr("abbrev"), ", ", jstr("full_name"), ", ",
                    jarr(jstr.(EM_COMP_BASIS)), "],")
        println(io, jstr("_ambiguous_"), ": ", jarr(jstr.(sort(ambig))), ",")
        for (k, n) in enumerate(allnm)
            print(io, jstr(n), ": [", jstr(n), ", ", jstr(get(full, n, "")), ", ",
                      jarr(jnum.(pick[n])), "]")
            println(io, k == length(allnm) ? "" : ",")
        end
        println(io, "}")
    end
    println(" Wrote ", em_path, " (", length(allnm), " names, ", length(ambig),
            " with database-dependent compositions)")

    # solution phases: every short and citation-tagged name any database uses
    phases = Set{String}()
    for db in get_db_list()
        inf = retrieve_solution_phase_information(db)
        union!(phases, inf.ss_name)
        for s in inf.data_ss; isempty(s.ss_fName) || push!(phases, s.ss_fName); end
    end
    ss_path = normpath(joinpath(@__DIR__, "..", "julia", "ss_name.json"))
    sorted  = sort(collect(phases))
    open(ss_path, "w") do io
        println(io, "{")
        for (k, ph) in enumerate(sorted)
            fam = sort(unique(reduce(vcat,
                     [v for ((db, ss), v) in SOLVUS_FAMILY if ss == ph]; init = String[])))
            isempty(fam) && (fam = [ph])
            print(io, jstr(ph), ": [", jstr(get(full, ph, "")), ", [",
                      jarr(jstr.(fam)), ", ", jarr(jstr.([get(full, d, "") for d in fam])), "]]")
            println(io, k == length(sorted) ? "" : ",")
        end
        println(io, "}")
    end
    println(" Wrote ", ss_path, " (", length(sorted), " solution phases)")
end

write_name_tables()
